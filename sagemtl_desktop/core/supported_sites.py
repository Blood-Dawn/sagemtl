def get_all_supported_sites_flat() -> list[str]:
    """Get a flat, sorted list of all supported sites."""
    all_sites = set()
    for sites in SUPPORTED_SITES_BY_LANGUAGE.values():
        all_sites.update(sites)
    return sorted(list(all_sites))


def get_supported_sites_formatted() -> list[str]:
    """Get supported sites formatted as a user-friendly list with language grouping."""
    result = []
    for language in sorted(SUPPORTED_SITES_BY_LANGUAGE.keys()):
        sites = SUPPORTED_SITES_BY_LANGUAGE[language]
        if sites:
            # Add language header
            result.append(f"\n--- {language} ({len(sites)} sites) ---")
            # Add sorted sites for this language
            result.extend(sorted(sites))
    return result
